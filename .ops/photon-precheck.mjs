import { readFileSync } from "node:fs"
import admin from "firebase-admin"
let raw = readFileSync(".env","utf8").match(/^FIREBASE_SERVICE_ACCOUNT_JSON=(.*)$/m)[1].trim()
if ((raw.startsWith("'")&&raw.endsWith("'"))||(raw.startsWith('"')&&raw.endsWith('"'))) raw=raw.slice(1,-1)
admin.initializeApp({ credential: admin.credential.cert(JSON.parse(raw)), projectId: "wekruit-5f89b" })
const db = admin.firestore()

const j = (await db.collection("pa-jobs").doc("photon-backend-engineer-high-concurrency").get()).data()
console.log("recruiterBoard.active =", j.recruiterBoard?.active)
console.log("publicId =", j.publicId)
console.log("checklist ids:", j.recruiterBoard.checklist.groups.map(g=>`${g.kind}:${g.items.map(i=>i.id).join("|")}`).join("\n   "))
console.log("submitFields:", JSON.stringify(j.recruiterBoard?.submitFields ?? null))

const since = new Date(Date.now()-20*3600*1000).toISOString()
const all = (await db.collection("pa-users").where("createdAt",">=",since).get()).docs.map(d=>({id:d.id,...d.data()}))
const yc = all.filter(u=>u.ycIntake||String(u.source??"").includes("yc")||String(u.firstTouchCampaign??"").includes("yc"))
const enriched = yc.filter(u=>u.experienceHighlights?.length || typeof u.coresignalEmployeeId==="number")
const real = enriched.filter(u=>typeof u.linkedinUrl==="string" && /linkedin\.com\/in\//.test(u.linkedinUrl))
const placeholder = enriched.filter(u=>typeof u.linkedinUrl==="string" && u.linkedinUrl.includes("/oauth-linked/"))
console.log(`\nYC=${yc.length} enriched=${enriched.length} realLinkedIn=${real.length} placeholder=${placeholder.length} noUrl=${enriched.length-real.length-placeholder.length}`)
console.log("names present:", enriched.filter(u=>u.displayName||u.linkedinOauthName).length)
console.log("emails present:", enriched.filter(u=>u.email||u.linkedinOauthEmail).length)

console.log("\n===== sample submission doc keys =====")
const s = await db.collection("pa-recruiter-submissions").limit(1).get()
const d = s.docs[0].data()
console.log(Object.keys(d).join(", "))
console.log("candidate:", JSON.stringify(d.candidate))
console.log("checklist:", JSON.stringify(d.checklist))
console.log("score:", JSON.stringify(d.score))
console.log("submitter:", JSON.stringify(d.submitter))
console.log("consent:", JSON.stringify(d.candidateConsent), d.candidateConsentStatus)
console.log("callerSource:", d.callerSource, "| mode:", d.submissionMode, "| status:", d.status)
process.exit(0)
